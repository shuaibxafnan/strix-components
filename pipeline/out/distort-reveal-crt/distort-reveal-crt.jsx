"use client";

import { useEffect, useRef } from "react";

export default function DistortRevealCrt({
  bgColor = "#000",
  textColor = "#fff",
  lastHeadingColor = "#000",
  sectionSpacingY = 40,
  sectionWidthPct = 60,
  h1FontSize = 8,
  h2FontSize = 6,
  pFontSize = 3,
  heading1Text = "The reality,",
  heading2Text = "...is always,",
  heading3Text = "...distorted.",
  paragraph1Text = "Obviously, this is just a test text — but how do you know? There is certainly a writer of this text, someone who exists. Even if it was automatically generated by some tool or AI, there must have been a text, somewhere, used as training material. So we cannot escape the spirit — the vibe — the shadow it casts. It comes from the soul, buried deep in unconscious limbo.",
  paragraph2Text = "Somewhere between the folds, something breathes. Not a presence, but the memory of having been watched. Syntax curls back on itself, a serpent swallowing not its tail, but its own shadow. Read again. You missed it the first time. You always do.",
  paragraph3Text = "And if the soul remains, so too does its intent — not always clear, not always benevolent. What was the writer thinking? Or worse — what was it trying not to think? Language is a veil, but veils are thin when backlit by desire, or fear, or guilt. Read carefully. Something watches back when you stare too long into a sentence.",
  image1Src = "https://picsum.photos/id/737/800/600",
  image2Src = "https://picsum.photos/id/100/800/600",
  image3Src = "https://picsum.photos/id/102/800/600",
  image4Src = "https://picsum.photos/id/972/800/600",
  vignetteStrength = 1.8,
  ditherAmount = 0.1,
  chromaticAberration = 0.0015,
  glitchBlurFactor = 0.3,
  scrollPadding = false,
  className = "",
}) {
  const containerRef = useRef(null);
  const vfxRef = useRef(null);

  useEffect(() => {
    let cancelled = false;

    const mainShader =
      "precision highp float;\n" +
      "uniform sampler2D src;\n" +
      "uniform vec2 offset;\n" +
      "uniform vec2 resolution;\n" +
      "uniform float time;\n" +
      "out vec4 outColor;\n" +
      "vec4 readTex(vec2 uv) {\n" +
      "  vec4 c = texture(src, uv);\n" +
      "  c.a *= smoothstep(.5, .499, abs(uv.x - .5)) * smoothstep(.5, .499, abs(uv.y - .5));\n" +
      "  return c;\n" +
      "}\n" +
      "vec2 zoom(vec2 uv, float t) {\n" +
      "  return (uv - .5) * t + .5;\n" +
      "}\n" +
      "float rand(vec3 p) {\n" +
      "  return fract(sin(dot(p, vec3(829., 4839., 432.))) * 39428.);\n" +
      "}\n" +
      "void main() {\n" +
      "  vec2 uv = (gl_FragCoord.xy - offset) / resolution;\n" +
      "  vec2 p = uv * 2. - 1.;\n" +
      "  p.x *= resolution.x / resolution.y;\n" +
      "  float l = length(p);\n" +
      "  float dist = pow(l, 2.) * " +
      glitchBlurFactor.toFixed(4) +
      ";\n" +
      "  dist = smoothstep(0., 1., dist);\n" +
      "  uv = zoom(uv, 0.5 + dist);\n" +
      "  float a = atan(p.y, p.x);\n" +
      "  float rd = rand(vec3(a, time, 0));\n" +
      "  uv = (uv - .5) * (1.0 + rd * pow(l * 0.7, 3.) * 0.3) + .5;\n" +
      "  vec2 uvr = uv;\n" +
      "  vec2 uvg = uv;\n" +
      "  vec2 uvb = uv;\n" +
      "  float d = (1. + sin(uv.y * 20. + time * 3.) * 0.1) * 0.05;\n" +
      "  uvr.x += " +
      chromaticAberration.toFixed(4) +
      ";\n" +
      "  uvb.x -= " +
      chromaticAberration.toFixed(4) +
      ";\n" +
      "  uvr = zoom(uvr, 1. + d * l * l);\n" +
      "  uvb = zoom(uvb, 1. - d * l * l);\n" +
      "  vec4 cr = readTex(uvr);\n" +
      "  vec4 cg = readTex(uvg);\n" +
      "  vec4 cb = readTex(uvb);\n" +
      "  outColor = vec4(cr.r, cg.g, cb.b, (cr.a + cg.a + cb.a) / 1.);\n" +
      "  vec4 deco;\n" +
      "  float res = resolution.y;\n" +
      "  deco += (sin(uv.y * res * .7 + time * 100.) * sin(uv.y * res * .3 - time * 130.)) * 0.05;\n" +
      "  deco += smoothstep(.01, .0, min(fract(uv.x * 20.), fract(uv.y * 20.))) * 0.1;\n" +
      "  outColor += deco * smoothstep(2., 0., l);\n" +
      "  outColor *= " +
      vignetteStrength.toFixed(3) +
      " - l * l;\n" +
      "  outColor += rand(vec3(p, time)) * " +
      ditherAmount.toFixed(3) +
      ";\n" +
      "}\n";

    const elementShader =
      "precision highp float;\n" +
      "uniform sampler2D src;\n" +
      "uniform vec2 offset;\n" +
      "uniform vec2 resolution;\n" +
      "uniform float time;\n" +
      "uniform float id;\n" +
      "out vec4 outColor;\n" +
      "vec4 readTex(vec2 uv) {\n" +
      "  vec4 c = texture(src, uv);\n" +
      "  c.a *= smoothstep(.5, .499, abs(uv.x - .5)) * smoothstep(.5, .499, abs(uv.y - .5));\n" +
      "  return c;\n" +
      "}\n" +
      "float rand(vec2 p) {\n" +
      "  return fract(sin(dot(p, vec2(829., 483.))) * 394.);\n" +
      "}\n" +
      "void main() {\n" +
      "  vec2 uv = (gl_FragCoord.xy - offset) / resolution;\n" +
      "  vec2 uvr = uv, uvg = uv, uvb = uv;\n" +
      "  float r = rand(vec2(floor(time * 43.), id));\n" +
      "  if (r > 0.8) {\n" +
      "    float y = sin(floor(uv.y / 0.07)) + sin(floor(uv.y / 0.003 + time));\n" +
      "    float f = rand(vec2(y, floor(time * 5.0) + id)) * 2. - 1.;\n" +
      "    uvr.x += f * 0.1;\n" +
      "    uvg.x += f * 0.2;\n" +
      "    uvb.x += f * 0.3;\n" +
      "  }\n" +
      "  float r2 = rand(vec2(floor(time * 37.), id + 10.));\n" +
      "  if (r2 > 0.9) {\n" +
      "    uvr.x += sin(uv.y * 7. + time + id + 1.) * 0.03;\n" +
      "    uvg.x += sin(uv.y * 5. + time + id + 2.) * 0.03;\n" +
      "    uvb.x += sin(uv.y * 3. + time + id + 3.) * 0.03;\n" +
      "  }\n" +
      "  vec4 cr = readTex(uvr);\n" +
      "  vec4 cg = readTex(uvg);\n" +
      "  vec4 cb = readTex(uvb);\n" +
      "  outColor = vec4(cr.r, cg.g, cb.b, (cr.a + cg.a + cb.a) / 1.);\n" +
      "}\n";

    import("@vfx-js/core")
      .then(({ VFX }) => {
        if (cancelled || !containerRef.current) return;

        const vfx = new VFX({
          scrollPadding,
          postEffect: { shader: mainShader },
        });
        if (vfxRef.current) vfxRef.current.destroy();
        vfxRef.current = vfx;

        let i = 0;
        const els = containerRef.current.querySelectorAll("img,h1,h2,p");
        els.forEach((el) => {
          const z = el.getAttribute("data-z");
          vfx.add(el, {
            shader: elementShader,
            uniforms: { id: i++ },
            zIndex: z ? parseInt(z, 10) : 0,
          });
        });
      })
      .catch((e) =>
        console.error("[DistortRevealCrt] VFX-JS load failed:", e.message),
      );

    return () => {
      cancelled = true;
      if (vfxRef.current) {
        vfxRef.current.destroy();
        vfxRef.current = null;
      }
    };
  }, [
    scrollPadding,
    vignetteStrength,
    ditherAmount,
    chromaticAberration,
    glitchBlurFactor,
  ]);

  const sectionStyle = {
    margin: `${sectionSpacingY}vh ${(100 - sectionWidthPct) / 2}%`,
    width: `${sectionWidthPct}%`,
    color: textColor,
  };

  return (
    <div
      ref={containerRef}
      className={`w-full overflow-x-hidden ${className}`}
      style={{ backgroundColor: bgColor }}
    >
      <section style={sectionStyle}>
        <h1 className="m-0 opacity-0" style={{ fontSize: `${h1FontSize}vh` }}>
          {heading1Text}
        </h1>
        <img src={image1Src} alt="" className="w-full my-8 opacity-0" />
        <p className="m-0 opacity-0" style={{ fontSize: `${pFontSize}vh` }}>
          {paragraph1Text}
        </p>
      </section>

      <section style={sectionStyle}>
        <div className="text-right">
          <h1 className="m-0 opacity-0" style={{ fontSize: `${h1FontSize}vh` }}>
            {heading2Text}
          </h1>
        </div>

        <div className="flex flex-col sm:flex-row gap-4 my-8">
          <img src={image2Src} alt="" className="max-w-full sm:max-w-[40%] m-0 opacity-0" />
          <p className="m-0 opacity-0" style={{ fontSize: `${pFontSize}vh` }}>
            {paragraph2Text}
          </p>
        </div>

        <div className="flex flex-col sm:flex-row gap-4 my-8">
          <p className="m-0 opacity-0" style={{ fontSize: `${pFontSize}vh` }}>
            {paragraph3Text}
          </p>
          <img src={image3Src} alt="" className="max-w-full sm:max-w-[40%] m-0 opacity-0" />
        </div>
      </section>

      <section
        className="grid place-items-center mb-0"
        style={{ ...sectionStyle, marginBottom: 0 }}
      >
        <img
          src={image4Src}
          alt=""
          className="w-full m-0 opacity-0 [grid-area:1/1]"
        />
        <h2
          data-z="1"
          className="opacity-0 [grid-area:1/1]"
          style={{
            fontSize: `${h2FontSize}vh`,
            margin: "47vh 0",
            color: lastHeadingColor,
          }}
        >
          {heading3Text}
        </h2>
      </section>
    </div>
  );
}
